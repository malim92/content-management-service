-- Initial CMS schema.

CREATE TABLE contents (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content_key VARCHAR(255) NOT NULL,
    title       VARCHAR(500) NOT NULL,
    content     TEXT         NOT NULL,
    language    VARCHAR(10)  NOT NULL,
    status      VARCHAR(20)  NOT NULL,
    version     BIGINT       NOT NULL DEFAULT 0,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT uk_contents_key_language UNIQUE (content_key, language),
    CONSTRAINT chk_contents_status CHECK (status IN ('DRAFT', 'PUBLISHED', 'ARCHIVED'))
);

-- Read-path indexes for the search API.
-- The unique constraint above already provides an index on (content_key, language).
CREATE INDEX idx_contents_status      ON contents (status);
CREATE INDEX idx_contents_language    ON contents (language);
CREATE INDEX idx_contents_created_at  ON contents (created_at);
